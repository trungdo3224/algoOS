import React, { useState } from 'react';
import { 
  Play, 
  Copy, 
  Download, 
  Eye, 
  EyeOff, 
  Clock, 
  Zap, 
  Target, 
  Lightbulb, 
  AlertTriangle,
  Code,
  FileText,
  CheckCircle
} from 'lucide-react';
import Button from '../ui/Button';
import Card from '../ui/Card';
import type { GeneratedProblemOutput } from '../../lib/supabase';

interface GeneratedProblemDisplayProps {
  problem: GeneratedProblemOutput;
  onSimulateSolving: () => void;
}

const GeneratedProblemDisplay: React.FC<GeneratedProblemDisplayProps> = ({
  problem,
  onSimulateSolving
}) => {
  const [showHints, setShowHints] = useState(false);
  const [showAssumptions, setShowAssumptions] = useState(false);
  const [showEdgeCases, setShowEdgeCases] = useState(false);
  const [copiedSection, setCopiedSection] = useState<string | null>(null);

  const getDifficultyColor = (difficulty: string) => {
    switch (difficulty) {
      case 'Easy':
        return 'text-green-600 bg-green-50 border-green-200';
      case 'Medium':
        return 'text-yellow-600 bg-yellow-50 border-yellow-200';
      case 'Hard':
        return 'text-red-600 bg-red-50 border-red-200';
      default:
        return 'text-gray-600 bg-gray-50 border-gray-200';
    }
  };

  const copyToClipboard = async (text: string, section: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopiedSection(section);
      setTimeout(() => setCopiedSection(null), 2000);
    } catch (err) {
      console.error('Failed to copy text: ', err);
    }
  };

  const exportProblem = () => {
    const problemText = `
# ${problem.title}

**Difficulty:** ${problem.difficulty}
**Tags:** ${problem.tags.join(', ')}
**Pattern:** ${problem.algorithmicPattern}

## Problem Description
${problem.description}

## Input Format
${problem.inputFormat}

## Output Format
${problem.outputFormat}

## Examples
${problem.examples.map((example, index) => `
### Example ${index + 1}
**Input:**
\`\`\`
${example.input}
\`\`\`

**Output:**
\`\`\`
${example.output}
\`\`\`

**Explanation:** ${example.explanation}
`).join('\n')}

## Constraints
${problem.constraints.map(constraint => `- ${constraint}`).join('\n')}

${problem.hints && problem.hints.length > 0 ? `
## Hints
${problem.hints.map(hint => `- ${hint}`).join('\n')}
` : ''}

## Complexity Analysis
- **Time Complexity:** ${problem.timeComplexity}
- **Space Complexity:** ${problem.spaceComplexity}

---
*Generated by AlgoMind Reverse Challenge on ${problem.generatedAt.toLocaleString()}*
    `.trim();

    const blob = new Blob([problemText], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${problem.title.replace(/\s+/g, '-').toLowerCase()}.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <Card className="bg-gradient-to-r from-green-50 to-blue-50 border-green-200">
        <div className="flex items-start justify-between">
          <div className="flex-1">
            <div className="flex items-center space-x-3 mb-3">
              <div className="h-10 w-10 bg-gradient-to-r from-green-500 to-blue-600 rounded-lg flex items-center justify-center">
                <Target className="h-6 w-6 text-white" />
              </div>
              <div>
                <h2 className="text-2xl font-bold text-gray-900">{problem.title}</h2>
                <p className="text-sm text-gray-600">Generated from your code analysis</p>
              </div>
            </div>
            
            <div className="flex flex-wrap items-center gap-3 mb-4">
              <span className={`px-3 py-1 rounded-full text-sm font-medium border ${getDifficultyColor(problem.difficulty)}`}>
                {problem.difficulty}
              </span>
              <span className="px-3 py-1 bg-purple-100 text-purple-800 text-sm rounded-full">
                {problem.algorithmicPattern}
              </span>
              {problem.tags.slice(0, 3).map((tag, index) => (
                <span key={index} className="px-2 py-1 bg-blue-100 text-blue-800 text-xs rounded">
                  {tag}
                </span>
              ))}
              {problem.tags.length > 3 && (
                <span className="text-xs text-gray-500">+{problem.tags.length - 3} more</span>
              )}
            </div>

            <div className="grid grid-cols-2 md:grid-cols-4 gap-4 text-sm">
              <div className="flex items-center">
                <Clock className="h-4 w-4 text-blue-500 mr-2" />
                <span className="text-gray-700">Time: {problem.timeComplexity}</span>
              </div>
              <div className="flex items-center">
                <Zap className="h-4 w-4 text-purple-500 mr-2" />
                <span className="text-gray-700">Space: {problem.spaceComplexity}</span>
              </div>
              <div className="flex items-center">
                <FileText className="h-4 w-4 text-green-500 mr-2" />
                <span className="text-gray-700">{problem.examples.length} Examples</span>
              </div>
              <div className="flex items-center">
                <AlertTriangle className="h-4 w-4 text-orange-500 mr-2" />
                <span className="text-gray-700">{problem.constraints.length} Constraints</span>
              </div>
            </div>
          </div>

          <div className="flex flex-col space-y-2 ml-4">
            <Button
              onClick={onSimulateSolving}
              className="bg-gradient-to-r from-blue-500 to-purple-600 hover:from-blue-600 hover:to-purple-700 text-white"
              rightIcon={<Play className="h-4 w-4" />}
            >
              Simulate Solving
            </Button>
            <Button
              onClick={exportProblem}
              variant="outline"
              size="sm"
              leftIcon={<Download className="h-4 w-4" />}
            >
              Export
            </Button>
          </div>
        </div>
      </Card>

      {/* Problem Description */}
      <Card>
        <div className="flex items-center justify-between mb-4">
          <h3 className="text-lg font-semibold text-gray-900">Problem Statement</h3>
          <Button
            onClick={() => copyToClipboard(problem.description, 'description')}
            variant="ghost"
            size="sm"
            leftIcon={copiedSection === 'description' ? <CheckCircle className="h-4 w-4" /> : <Copy className="h-4 w-4" />}
          >
            {copiedSection === 'description' ? 'Copied!' : 'Copy'}
          </Button>
        </div>
        <div className="prose prose-sm max-w-none">
          <p className="text-gray-700 leading-relaxed">{problem.description}</p>
        </div>
      </Card>

      {/* Input/Output Format */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        <Card>
          <h3 className="text-lg font-semibold text-gray-900 mb-3 flex items-center">
            <Code className="h-5 w-5 mr-2 text-blue-600" />
            Input Format
          </h3>
          <div className="bg-gray-50 rounded-lg p-4">
            <p className="text-gray-700 text-sm">{problem.inputFormat}</p>
          </div>
        </Card>

        <Card>
          <h3 className="text-lg font-semibold text-gray-900 mb-3 flex items-center">
            <Code className="h-5 w-5 mr-2 text-green-600" />
            Output Format
          </h3>
          <div className="bg-gray-50 rounded-lg p-4">
            <p className="text-gray-700 text-sm">{problem.outputFormat}</p>
          </div>
        </Card>
      </div>

      {/* Examples */}
      <Card>
        <h3 className="text-lg font-semibold text-gray-900 mb-4 flex items-center">
          <FileText className="h-5 w-5 mr-2 text-purple-600" />
          Examples
        </h3>
        <div className="space-y-6">
          {problem.examples.map((example, index) => (
            <div key={index} className="border border-gray-200 rounded-lg p-4">
              <h4 className="font-medium text-gray-900 mb-3">Example {index + 1}</h4>
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mb-3">
                <div>
                  <div className="text-sm font-medium text-gray-700 mb-1">Input:</div>
                  <pre className="bg-gray-50 rounded p-3 text-sm text-gray-800 overflow-x-auto">
                    {example.input}
                  </pre>
                </div>
                <div>
                  <div className="text-sm font-medium text-gray-700 mb-1">Output:</div>
                  <pre className="bg-gray-50 rounded p-3 text-sm text-gray-800 overflow-x-auto">
                    {example.output}
                  </pre>
                </div>
              </div>
              {example.explanation && (
                <div>
                  <div className="text-sm font-medium text-gray-700 mb-1">Explanation:</div>
                  <p className="text-sm text-gray-600">{example.explanation}</p>
                </div>
              )}
            </div>
          ))}
        </div>
      </Card>

      {/* Constraints */}
      <Card>
        <h3 className="text-lg font-semibold text-gray-900 mb-4 flex items-center">
          <AlertTriangle className="h-5 w-5 mr-2 text-orange-600" />
          Constraints
        </h3>
        <div className="space-y-2">
          {problem.constraints.map((constraint, index) => (
            <div key={index} className="flex items-start">
              <span className="w-2 h-2 bg-orange-500 rounded-full mt-2 mr-3 flex-shrink-0"></span>
              <span className="text-gray-700">{constraint}</span>
            </div>
          ))}
        </div>
      </Card>

      {/* Optional Sections */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
        {/* Hints */}
        {problem.hints && problem.hints.length > 0 && (
          <Card>
            <div className="flex items-center justify-between mb-3">
              <h3 className="text-lg font-semibold text-gray-900 flex items-center">
                <Lightbulb className="h-5 w-5 mr-2 text-yellow-600" />
                Hints
              </h3>
              <button
                onClick={() => setShowHints(!showHints)}
                className="text-sm text-blue-600 hover:text-blue-700 flex items-center"
              >
                {showHints ? <EyeOff className="h-4 w-4 mr-1" /> : <Eye className="h-4 w-4 mr-1" />}
                {showHints ? 'Hide' : 'Show'}
              </button>
            </div>
            {showHints && (
              <div className="space-y-2">
                {problem.hints.map((hint, index) => (
                  <div key={index} className="flex items-start">
                    <span className="w-2 h-2 bg-yellow-500 rounded-full mt-2 mr-3 flex-shrink-0"></span>
                    <span className="text-gray-700 text-sm">{hint}</span>
                  </div>
                ))}
              </div>
            )}
          </Card>
        )}

        {/* Inferred Assumptions */}
        {problem.inferredAssumptions.length > 0 && (
          <Card>
            <div className="flex items-center justify-between mb-3">
              <h3 className="text-lg font-semibold text-gray-900 flex items-center">
                <Target className="h-5 w-5 mr-2 text-blue-600" />
                Assumptions
              </h3>
              <button
                onClick={() => setShowAssumptions(!showAssumptions)}
                className="text-sm text-blue-600 hover:text-blue-700 flex items-center"
              >
                {showAssumptions ? <EyeOff className="h-4 w-4 mr-1" /> : <Eye className="h-4 w-4 mr-1" />}
                {showAssumptions ? 'Hide' : 'Show'}
              </button>
            </div>
            {showAssumptions && (
              <div className="space-y-2">
                {problem.inferredAssumptions.map((assumption, index) => (
                  <div key={index} className="flex items-start">
                    <span className="w-2 h-2 bg-blue-500 rounded-full mt-2 mr-3 flex-shrink-0"></span>
                    <span className="text-gray-700 text-sm">{assumption}</span>
                  </div>
                ))}
              </div>
            )}
          </Card>
        )}

        {/* Hidden Edge Cases */}
        {problem.hiddenEdgeCases.length > 0 && (
          <Card>
            <div className="flex items-center justify-between mb-3">
              <h3 className="text-lg font-semibold text-gray-900 flex items-center">
                <AlertTriangle className="h-5 w-5 mr-2 text-red-600" />
                Edge Cases
              </h3>
              <button
                onClick={() => setShowEdgeCases(!showEdgeCases)}
                className="text-sm text-blue-600 hover:text-blue-700 flex items-center"
              >
                {showEdgeCases ? <EyeOff className="h-4 w-4 mr-1" /> : <Eye className="h-4 w-4 mr-1" />}
                {showEdgeCases ? 'Hide' : 'Show'}
              </button>
            </div>
            {showEdgeCases && (
              <div className="space-y-2">
                {problem.hiddenEdgeCases.map((edgeCase, index) => (
                  <div key={index} className="flex items-start">
                    <span className="w-2 h-2 bg-red-500 rounded-full mt-2 mr-3 flex-shrink-0"></span>
                    <span className="text-gray-700 text-sm">{edgeCase}</span>
                  </div>
                ))}
              </div>
            )}
          </Card>
        )}
      </div>

      {/* Footer */}
      <div className="text-center py-4 border-t border-gray-200">
        <p className="text-sm text-gray-500">
          Generated by Gemini AI • {problem.generatedAt.toLocaleString()}
        </p>
      </div>
    </div>
  );
};

export default GeneratedProblemDisplay;